    def test_style_inheritance_merged_edges_and_cell_placement(self):
        sheet = self.workbook("formatting", {}).active
        self.assertEqual({str(r) for r in sheet.merged_cells.ranges}, {"A1:B2"})
        cell = sheet["A1"]
        self.assertEqual((cell.font.name, cell.font.sz, cell.font.bold), ("DejaVu Sans", 16, True))
        self.assertEqual(cell.font.color.rgb, "FF112233")
        self.assertEqual(cell.fill.fgColor.rgb, "FFFFFF00")
        self.assertEqual((cell.alignment.horizontal, cell.alignment.vertical, cell.alignment.wrap_text), ("center", "top", True))
        # Normal openpyxl mode replaces merged boundary cells with synthesized
        # MergedCells; default-border colors can override their serialized colors.
        # Streaming mode reads the actual emitted cells without that reconstruction.
        with READER_LOCK, warnings.catch_warnings():
            warnings.simplefilter("error")
            raw_book = openpyxl.load_workbook(ARTIFACTS / (self._testMethodName + ".xlsx"), read_only=True)
            try:
                top, right = raw_book.active["B1"].border.top, raw_book.active["B2"].border.right
                self.assertEqual((top.style, top.color.rgb), ("medium", "FF00FF00"))
                self.assertEqual((right.style, right.color.rgb), ("thick", "FF0000FF"))
            finally:
                raw_book.close()
        self.assertEqual(sheet["C1"].number_format, "0.000")
        self.assertEqual(sheet["C1"].font.sz, 12)
        self.assertTrue(sheet["C1"].font.bold)
        self.assertEqual(sheet["C2"].value, "after merge")
        self.assertTrue(30 <= sheet.column_dimensions["C"].width < 31)
        self.assertGreaterEqual(sheet.row_dimensions[1].height, 35)

