    def test_formula_whitespace_cross_sheet_references_and_local_names(self):
        book = self.workbook("names", {})
        self.assertEqual(book.sheetnames, ["Alpha", "Beta"])
        self.assertEqual(book["Alpha"]["A2"].value, "=SUM($A$1:$B$1)")
        self.assertEqual(book["Beta"]["A2"].value, "=Alpha!$A$1+B1")
        self.assertEqual(book["Alpha"]["A2"].data_type, "f")
        self.assertNotIn("Anchor", book.defined_names)
        for name, target in [("Alpha", "$A$1"), ("Beta", "$B$1")]:
            self.assertEqual(list(book[name].defined_names["Anchor"].destinations), [(name, target + ":" + target)])
        self.assertEqual(list(book["Alpha"].defined_names["InputRange"].destinations), [("Alpha", "$A$1:$B$1")])
        self.assertEqual(list(book["Beta"].defined_names["InputRange"].destinations), [("Beta", "$B$1:$B$1")])

    def test_print_area_paper_orientation_and_frozen_scrolled_headers(self):
        for from_start in [False, True]:
            for orientation, paper, number in [("Portrait", "A4", "9"), ("Landscape", "A3", "8")]:
                with self.subTest(from_start=from_start, orientation=orientation):
                    sheet = self.workbook("printing", {"fromStart": from_start, "orientation": orientation, "paper": paper},
                                          label=f"print-{from_start}-{paper}").active
                    self.assertEqual(sheet.page_setup.orientation, orientation.lower())
                    self.assertEqual(str(sheet.page_setup.paperSize), number)
                    # OOXML CT_PageSetup defines omitted fitToWidth as 1; openpyxl exposes None.
                    self.assertEqual((sheet.page_setup.fitToWidth if sheet.page_setup.fitToWidth is not None else 1, sheet.page_setup.fitToHeight), (1, 0))
                    self.assertTrue(sheet.sheet_properties.pageSetUpPr.fitToPage)
                    self.assertIn("$A$1:$A$4", sheet.print_area)
                    self.assertEqual(sheet.print_title_rows, "$2:$3")
                    self.assertEqual(sheet.sheet_view.view, "pageBreakPreview")
                    self.assertEqual(sheet.sheet_view.pane.ySplit, 3 if from_start else 2)
                    self.assertEqual(sheet.freeze_panes, "A4" if from_start else "A3")
                    if not from_start:
                        self.assertEqual(sheet.sheet_view.topLeftCell, "A2")
                    else:
                        self.assertNotEqual(sheet.sheet_view.topLeftCell, "A2")

