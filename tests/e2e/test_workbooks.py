    def test_setup_locale_and_module_state_are_isolated_in_concurrent_requests(self):
        def render(index):
            token = f"request-{index}-Україна"
            book = self.workbook("locale", {"token": token}, label=f"concurrent-{index}")
            return [book.active.cell(1, col).value for col in range(1, 4)]
        with ThreadPoolExecutor(max_workers=2) as workers:
            result = list(workers.map(render, range(12)))
        self.assertEqual(result, [["січень", f"request-{i}-Україна", 1] for i in range(12)])

    def test_large_and_empty_tables_have_no_truncated_or_phantom_rows(self):
        for count in [0, 1250]:
            with self.subTest(count=count):
                items = [{"id": f"{i:06d}", "amount": i / 4} for i in range(count)]
                sheet = self.workbook("table", {"items": items}, label=f"table-{count}").active
                self.assertEqual(sheet.max_row, count + 2)
                self.assertEqual(sheet.cell(count + 2, 1).value, "End")
                for index, item in enumerate(items, 2):
                    self.assertEqual(sheet.cell(index, 1).value, item["id"])
                    self.assertEqual(sheet.cell(index, 2).value, item["amount"])
                    self.assertEqual(sheet.cell(index, 3).value, f"=B{index}*2")

    def test_invalid_worksheet_name_is_rejected_then_service_recovers(self):
        status, headers, payload = self.request("values", self.values(sheet="invalid/name"), label="invalid-name")
        self.assertEqual(status, 422)
        self.assertEqual(headers.get_content_type(), "application/json")
        self.assertEqual(json.loads(payload)["error"]["code"], "invalid_workbook")
        self.assertEqual(self.workbook("values", self.values()).active.title, "Values")

    def test_sync_and_async_template_failures_cannot_return_partial_workbooks(self):
        for template, address, text in [("failure", "A1", "recovered"), ("async-failure", "A2", "complete")]:
            with self.subTest(template=template):
                status, headers, payload = self.request(template, {"fail": True, "secret": "do-not-leak"}, label=template+"-failure")
                self.assertEqual(status, 422)
                self.assertEqual(headers.get_content_type(), "application/json")
                self.assertNotIn(b"do-not-leak", payload)
                self.assertEqual(json.loads(payload)["error"]["code"], "template_failed")
                self.assertEqual(self.workbook(template, {"fail": False}, label=template+"-recovery").active[address].value, text)


